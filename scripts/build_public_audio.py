"""Extract the approved playback adapter without publishing/editor capabilities."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    text = (ROOT / "app/static/art/sound-studio.js").read_text()
    text = text.replace("const profiles=(()=>{try{return JSON.parse(localStorage.getItem(KEY)||'{}')||{};}catch(_){return {};}})();", "const profiles={};")
    text = text.replace("let cloudFetch=null, adminKey=sessionStorage.getItem('uno-sound-admin-key')||'';", "let cloudFetch=null;")
    start, end = text.index("function hasAdminKey()"), text.index("let database=null")
    text = text[:start] + "function cloudStatus(){return {ready:cloudReady,revision:cloudRevision,online:cloudProfiles.size,error:cloudError,admin:false};}\n" + text[end:]
    start, end = text.index("function setRepeat("), text.index("function stopNode(")
    text = text[:start] + text[end:]
    text = text[:text.index("async function reset(")] + '''
window.UNOLuckSoundStudio={install(){window.UNOLuckSound?.installStudio?.(this);},
  isCustomized,play,stopLoop,stopPreview,stopCelebration,segmentDuration,
  prepareSplashMedia,playSplashGesture,stopSplashAudio,
  prepareMusicMedia,playMusicGesture,armMusicOnSplashGesture,
  activateMusicAtGameplay,isMusicMediaPlaying,isMusicWebAudioPlaying,isIOS,
  syncCloud,cloudStatus,publishedProfile,profile,getRepeat,mirrorConfig,
  get lastError(){return lastError;},get splashError(){return splashError;},
  get mediaUnlocked(){return mediaUnlocked;},
  get activeCelebrationCue(){return celebrationNode?.key||fallbackKey?.startsWith('jackpot-')&&fallbackKey||null;}
};
window.UNOLuckSoundStudio.install();
void syncCloud();
document.addEventListener('visibilitychange',()=>{if(!document.hidden)void syncCloud(true);});
setInterval(()=>{if(!document.hidden)void syncCloud(true);},45000);
})();
'''
    return "/* Generated by scripts/build_public_audio.py; approved playback, read-only. */\n" + text


if __name__ == "__main__":
    (ROOT / "app/static/art/public-audio.js").write_text(build())
